using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Migrations;
using WebApplication1.Infrastructure;

namespace WebApplication1.Tests.Usuario;

public class PostgreSqlMigrationTests
{
    [Fact]
    public void InitialMigrationGeneratesPostgreSqlSchemaWithoutConnecting()
    {
        using var context = new RedditDbContext(new DbContextOptionsBuilder<RedditDbContext>()
            .UseNpgsql("Host=localhost;Database=MappingTest;Username=postgres").Options);

        var sql = context.GetService<IMigrator>().GenerateScript();

        foreach (var table in new[] { "Usuario", "Comunidade", "ComunidadeUsuario", "Post",
                     "Comentario", "UsuarioUpvotePost", "UsuarioUpvoteComentario" })
            Assert.Contains($"CREATE TABLE \"{table}\"", sql);

        Assert.Contains("GENERATED BY DEFAULT AS IDENTITY", sql);
        Assert.Contains("timestamp with time zone", sql);
        Assert.Contains("DEFAULT (CURRENT_TIMESTAMP)", sql);
        Assert.Contains("\"DataNascimento\" date", sql);
        Assert.Contains("\"Papel\" smallint", sql);
        Assert.Contains("\"ConteudoMarkdown\" boolean", sql);
        Assert.Contains("\"Texto\" character varying(3000)", sql);
        Assert.DoesNotContain("SqlServer:", sql);
        Assert.DoesNotContain("GETDATE", sql);
        Assert.DoesNotContain("nvarchar", sql);
    }
}
